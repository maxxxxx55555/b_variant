def T(s, **kw):
    """Подстановка значений в TeX-шаблон: <<имя>> -> значение (без возни с фигурными скобками)."""
    for k, v in kw.items():
        s = s.replace(f"<<{k}>>", str(v))
    return s


def UY(s):
    """Комплексные проводимости Y_k пишутся с чертой снизу."""
    return s.replace("Y_", r"\underline{Y}_")


def tn(x, nd=6):
    """Число для TeX с минимальным количеством знаков (строки не меняются)."""
    if isinstance(x, str):
        return x
    return f"{x:.{nd}g}".replace(".", "{,}")


def tmat(M, nd=6):
    rows = [" & ".join(tn(v, nd) for v in r) for r in M]
    return r"\begin{pmatrix}" + r" \\ ".join(rows) + r"\end{pmatrix}"


def tvec(v, nd=6):
    return r"\begin{pmatrix}" + r" \\ ".join(tn(x, nd) for x in v) + r"\end{pmatrix}"


def parse_log(name):
    d = {}
    for l in open(W + "spice/" + name, encoding="utf-8"):
        m = re.match(r"^\s*([\w@#\(\)\[\]\.,]+)\s*=\s*([-+0-9.eE]+)", l)
        if m and m.group(1) not in d:
            d[m.group(1)] = float(m.group(2))
    return d


def _clean(z, nd):
    """Обнуляет вещественные/мнимые части, которые при округлении дают «−0,000»."""
    re_, im_ = z.real, z.imag
    lim = 0.5 * 10 ** (-nd)
    return (0.0 if abs(re_) < lim else re_), (0.0 if abs(im_) < lim else im_)


def cplx_alg(z, nd=3):
    a, b = _clean(z, nd)
    return f"{f(a, nd)} {'+' if b >= 0 else MINUS} j{f(abs(b), nd)}"


def cplx_tex(z, nd=3):
    a, b = _clean(z, nd)
    return f"{tx(a, nd)} {'+' if b >= 0 else '-'} j\\,{tx(abs(b), nd)}"


def tran22_errors():
    """Максимальные отклонения мгновенных значений (ngspice - расчёт) после t = 20 мс."""
    phi, I, _ = task22.solve()
    d = np.loadtxt(W + "spice/tran22.txt")
    t = d[:, 0]
    col = {"L3": 5, "C2": 7, "C1": 9, "L1": 11, "L2": 13, "V1": 15}
    m = t >= 20e-3
    err = {}
    for k, c in col.items():
        a = abs(I[k]) * np.sin(task22.w * t[m] + np.angle(I[k]))
        err[k] = np.abs(d[m, c] - a).max()
    UL3 = task22.ZL(task22.L3) * I["L3"]
    a = abs(UL3) * np.sin(task22.w * t[m] + np.angle(UL3))
    err["UL3"] = np.abs((d[m, 1] - d[m, 3]) - a).max()
    return err


