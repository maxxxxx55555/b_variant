def sig(x, n=6):
    """Число с n значащими цифрами, десятичной запятой и настоящим минусом."""
    if abs(x) < 1e-12:
        return "0"
    s = f"{x:.{n}g}"
    if "e" in s:
        s = f"{x:.{n - 1}e}"
    return s.replace(".", ",").replace("-", MINUS)


